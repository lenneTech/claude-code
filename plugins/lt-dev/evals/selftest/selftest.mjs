#!/usr/bin/env node
// Judge self-test for the lt-dev eval suite.
//
// A judge-scored rubric is only trusted once it separates a good from a bad output. Each case below this directory
// replays fixed reference outputs (a good one and bad ones) through rubric files copied unchanged from the measured
// case, and states which verdict every rubric must reach. `claude plugin eval` runs them like any case; this script
// writes the copies right before a run and checks the verdicts afterwards.
//
//   node selftest.mjs sync              (re)write prompt.md, case.yaml, fixture.sh and graders/ of every self-test case
//   node selftest.mjs verify [result]   compare the verdicts in an aggregate-result.json (default: the newest one in
//                                       ../results/ that contains self-test cases) with the expectations;
//                                       --strict also fails on split judge votes (2 of 3)
//
// A self-test case is a directory here with a selftest.json:
//   {
//     "source": "agent/code-review-agent",          measured case, relative to evals/
//     "description": "...",                         what this reference is
//     "files": { "REPORT.md": "reference.md" },      workspace path -> file in this directory, placed by fixture.sh
//     "lastMessage": "REPORT.md",                   stands in for the final reply: rubrics without a focus judge it
//     "expect": { "<grader>": "pass" | "fail" }     rubrics to copy and the verdict each must reach
//   }
// Only the frontmatter of a copied rubric changes, and only where the source judges the final reply: the copy judges
// the `lastMessage` file instead. The rubric text is identical, so the self-test exercises exactly the judge prompt
// the measurement uses. Rubrics that already judge a workspace file are copied byte for byte.
//
// The generated files are git-ignored and written by `sync` before each self-test run, so they always match the
// rubrics they copy. Committed, they were 118 duplicate files that needed a CI step of their own to stay in step (and
// that step broke on Windows over path separators). Until `sync` runs, a self-test directory holds no prompt.md or
// case.yaml and is not an eval case at all, so a fresh checkout loads the suite without it.
//
// Dependency-free on purpose (Node 18+), like the other plugin scripts.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path, { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const EVALS = resolve(HERE, '..');
const GENERATED_NOTE = 'generated by ../selftest.mjs sync from selftest.json; edit the source rubric or selftest.json';

/**
 * The source path written into a generated copy. Always with forward slashes, so the copies are the same bytes on
 * every platform: `path.relative` on Windows returns backslashes.
 */
export function sourceLabel(from, to, impl = path) {
  return impl.relative(from, to).split(impl.sep).join('/');
}

class SelftestError extends Error {}

function fail(message) {
  throw new SelftestError(message);
}

function selftestCases() {
  return readdirSync(HERE)
    .filter((entry) => statSync(join(HERE, entry)).isDirectory() && existsSync(join(HERE, entry, 'selftest.json')))
    .sort()
    .map((entry) => {
      const dir = join(HERE, entry);
      let spec;
      try {
        spec = JSON.parse(readFileSync(join(dir, 'selftest.json'), 'utf8'));
      } catch (error) {
        fail(`${entry}/selftest.json: ${error.message}`);
      }
      for (const key of ['source', 'description', 'files', 'expect']) {
        if (!spec[key]) {
          fail(`${entry}/selftest.json: missing "${key}"`);
        }
      }
      return { dir, entry, name: `selftest-${entry}`, spec };
    });
}

/** Splits a markdown file with YAML frontmatter into its frontmatter lines and its body. */
function splitFrontmatter(text, where) {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
  if (!match) {
    fail(`${where}: no frontmatter`);
  }
  return { body: match[2], lines: match[1].split('\n') };
}

/** Builds the copy of one rubric for a self-test case. */
function copyRubric(testCase, graderName) {
  const sourcePath = join(EVALS, testCase.spec.source, 'graders', `${graderName}.md`);
  if (!existsSync(sourcePath)) {
    fail(`${testCase.entry}: rubric ${relative(EVALS, sourcePath)} does not exist`);
  }
  const text = readFileSync(sourcePath, 'utf8');
  const { body, lines } = splitFrontmatter(text, relative(EVALS, sourcePath));
  const type = (lines.find((line) => line.startsWith('type:')) ?? '').replace('type:', '').trim();
  const focusKey = type === 'regex' ? 'target' : 'focus';
  const focusLine = lines.find((line) => line.startsWith(`${focusKey}:`));
  const note = `# ${GENERATED_NOTE} (source: ${sourceLabel(EVALS, sourcePath)})`;
  if (!['llm', 'regex'].includes(type)) {
    fail(`${testCase.entry}: ${graderName} is a "${type}" grader; only llm and regex rubrics judge an output`);
  }
  if (!focusLine || /:\s*last_message\s*$/.test(focusLine)) {
    if (!testCase.spec.lastMessage || !testCase.spec.files[testCase.spec.lastMessage]) {
      fail(`${testCase.entry}: ${graderName} judges the final reply; set "lastMessage" to one of the "files"`);
    }
    const kept = lines.filter((line) => line !== focusLine);
    const at = kept.findIndex((line) => line.startsWith('type:')) + 1;
    kept.splice(at, 0, `${focusKey}: { source: file, path: ${testCase.spec.lastMessage} }`);
    return `---\n${note}\n${kept.join('\n')}\n---\n${body}`;
  }
  const path = /path:\s*([^\s}]+)/.exec(focusLine)?.[1];
  if (!/source:\s*file/.test(focusLine) || !path) {
    fail(`${testCase.entry}: ${graderName} has ${focusKey} "${focusLine}"; only the final reply or a file can be replayed`);
  }
  if (!testCase.spec.files[path]) {
    fail(`${testCase.entry}: ${graderName} judges ${path}; add it to "files"`);
  }
  return `---\n${note}\n${lines.join('\n')}\n---\n${body}`;
}

/** Every file sync writes for one case, as { relativePath: content }. */
function generatedFiles(testCase) {
  const { spec } = testCase;
  const source = spec.source.replace(/\/$/, '');
  const files = {};
  files['case.yaml'] = [
    `# ${GENERATED_NOTE}`,
    'schema_version: "1.1"',
    `name: ${testCase.name}`,
    'context:',
    '  scaffold_script: fixture.sh',
    '',
  ].join('\n');
  files['prompt.md'] = [
    '---',
    `description: ${JSON.stringify(`Judge self-test for ${source}: ${spec.description}`)}`,
    'tags: [selftest]',
    'runs: 1',
    'max_turns: 2',
    'timeout_seconds: 180',
    'model: haiku',
    '---',
    '',
    'Antworte nur mit: ok',
    '',
  ].join('\n');
  const copies = Object.entries(spec.files)
    .map(([target, from]) => {
      if (!existsSync(join(testCase.dir, from))) {
        fail(`${testCase.entry}: reference file ${from} does not exist`);
      }
      return `mkdir -p "$(dirname '${target}')" && cp "$HERE/${from}" '${target}'`;
    })
    .join('\n');
  files['fixture.sh'] = [
    '#!/usr/bin/env bash',
    `# ${GENERATED_NOTE}.`,
    `# Places the fixed reference output that the rubrics copied from ${source} judge.`,
    'set -eu',
    'HERE="$(cd "$(dirname "$0")" && pwd)"',
    copies,
    '',
  ].join('\n');
  for (const graderName of Object.keys(spec.expect)) {
    if (!['pass', 'fail'].includes(spec.expect[graderName])) {
      fail(`${testCase.entry}: expect.${graderName} must be "pass" or "fail"`);
    }
    files[`graders/${graderName}.md`] = copyRubric(testCase, graderName);
  }
  return files;
}

function staleGraders(testCase, files) {
  const graderDir = join(testCase.dir, 'graders');
  if (!existsSync(graderDir)) {
    return [];
  }
  return readdirSync(graderDir)
    .map((file) => `graders/${file}`)
    .filter((path) => !(path in files));
}

function sync() {
  for (const testCase of selftestCases()) {
    const files = generatedFiles(testCase);
    for (const stale of staleGraders(testCase, files)) {
      rmSync(join(testCase.dir, stale));
    }
    for (const [path, content] of Object.entries(files)) {
      const target = join(testCase.dir, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content, { mode: path === 'fixture.sh' ? 0o755 : 0o644 });
    }
    console.log(`synced ${testCase.entry} (${Object.keys(testCase.spec.expect).length} rubrics)`);
  }
}

/** Every self-test case with the files `sync` would write for it, built in memory. Throws on a broken definition. */
export function buildCases() {
  return selftestCases().map((testCase) => ({ entry: testCase.entry, files: generatedFiles(testCase) }));
}

function newestResult() {
  const resultsDir = join(EVALS, 'results');
  if (!existsSync(resultsDir)) {
    fail('no results directory; pass the aggregate-result.json path');
  }
  const candidates = readdirSync(resultsDir)
    .map((entry) => join(resultsDir, entry, 'aggregate-result.json'))
    .filter((path) => existsSync(path) && readFileSync(path, 'utf8').includes('"selftest-'))
    .sort();
  if (!candidates.length) {
    fail('no aggregate-result.json with self-test cases found; pass the path');
  }
  return candidates[candidates.length - 1];
}

function verify(args) {
  const strict = args.includes('--strict');
  const resultPath = args.find((arg) => !arg.startsWith('--')) ?? newestResult();
  const result = JSON.parse(readFileSync(resultPath, 'utf8'));
  const known = new Map(selftestCases().map((testCase) => [testCase.name, testCase]));
  const rows = [];
  let problems = 0;
  let splits = 0;
  const seen = new Set();
  for (const caseResult of result.cases ?? []) {
    const testCase = known.get(caseResult.name);
    if (!testCase) {
      continue;
    }
    seen.add(caseResult.name);
    const runs = caseResult.arms?.with ?? [];
    if (!runs.length) {
      rows.push([testCase.entry, '-', '-', 'no run', '']);
      problems++;
    }
    runs.forEach((run, index) => {
      const label = runs.length > 1 ? `${testCase.entry}#${index + 1}` : testCase.entry;
      if (run.error) {
        rows.push([label, '-', '-', `run error: ${run.error}`, '']);
        problems++;
      }
      for (const [graderName, expected] of Object.entries(testCase.spec.expect)) {
        const grader = (run.graders ?? []).find((entry) => entry.name === graderName);
        if (!grader) {
          rows.push([label, graderName, expected, 'missing', '']);
          problems++;
          continue;
        }
        const got = grader.passed ? 'pass' : 'fail';
        const votes = (grader.judgeVotes ?? []).map((vote) => (vote ? 'P' : 'F')).join('');
        const split = votes.length > 1 && new Set(votes).size > 1;
        const ok = got === expected;
        if (!ok) {
          problems++;
        } else if (split) {
          splits++;
        }
        rows.push([label, graderName, expected, ok ? (split ? 'ok (split)' : 'ok') : `WRONG: ${got}`, votes]);
      }
    });
  }
  const missing = [...known.keys()].filter((name) => !seen.has(name));
  const widths = [0, 1, 2, 3].map((column) =>
    Math.max(...[['case', 'rubric', 'expect', 'verdict'][column], ...rows.map((row) => row[column])].map((cell) => cell.length)),
  );
  const line = (cells) => cells.map((cell, column) => (column < 4 ? cell.padEnd(widths[column]) : cell)).join('  ');
  console.log(`Self-test verdicts from ${relative(process.cwd(), resultPath)}`);
  console.log(`judge: ${result.suite?.judgeModel ?? 'default'}`);
  console.log(line(['case', 'rubric', 'expect', 'verdict', 'votes']));
  rows.forEach((row) => console.log(line(row)));
  if (missing.length) {
    console.log(`not in this result: ${missing.join(', ')}`);
  }
  const failed = problems > 0 || (strict && splits > 0);
  console.log(
    `${problems} wrong or missing verdict(s), ${splits} split vote(s)${strict ? ' (strict)' : ''}: ${failed ? 'NOT TRUSTED' : 'trusted'}`,
  );
  process.exit(failed ? 1 : 0);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [command, ...rest] = process.argv.slice(2);
  try {
    if (command === 'sync') {
      sync();
    } else if (command === 'verify') {
      verify(rest);
    } else {
      console.error('usage: node selftest.mjs sync | verify [aggregate-result.json] [--strict]');
      process.exit(2);
    }
  } catch (error) {
    if (!(error instanceof SelftestError)) throw error;
    console.error(`selftest: ${error.message}`);
    process.exit(1);
  }
}
